"""Write RESULTS.md from pipeline outputs, so no number in the write-up is typed by hand.
  python -m saydo.report
"""
import json
import os

from . import config


def _l(n):
    p = os.path.join(config.OUT, n)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    st, sc, md, mk = _l("stats.json"), _l("scores.json"), _l("model.json"), _l("market.json")
    usage = _l("usage.json")
    L = ["# Say-Do results (auto-generated by `python -m saydo.report`)", "",
         f"Built {st['built']} · data as of {st['today']} · extraction/judging model `{st['models']['extract']}`", "",
         "## Corpus", "",
         f"- {st['companies']} companies, {st['calls']} earnings calls",
         f"- {st['promises']:,} promises extracted with verbatim-verified quotes; "
         f"{st['unverifiable_dropped']:,} model outputs rejected because the quote was not in the transcript",
         f"- {st['evidence_records']:,} promise×later-call checks; {st['evidence_with_status']:,} found evidence",
         f"- {st['scored']:,} promises resolved so far; outcomes: " +
         ", ".join(f"{k} {v}" for k, v in sorted(st["outcomes"].items(), key=lambda kv: -kv[1])), ""]
    if usage:
        L += [f"- Meta API usage for the full run: {usage}", ""]
    L += ["## Leaderboard (companies with ≥3 resolved promises)", "",
          "| Rank | Ticker | Say-Do | Grade | 80% CI | Resolved | Ghosted | Promises later delayed/cut | Revenue delivered ÷ guided |",
          "|---|---|---|---|---|---|---|---|---|"]
    rows = [c for c in sc["companies"] if c["n"] >= 3]
    for i, c in enumerate(rows, 1):
        L.append(f"| {i} | {c['ticker']} | {c['score']:.0f} | {c['grade']} | {c['ci80'][0]:.0f}–{c['ci80'][1]:.0f} | "
                 f"{c['n']} | {c['outcomes'].get('GHOSTED', 0)} | {c['goalpost_moves']} | "
                 f"{'' if c['revenue_delivery_ratio'] is None else format(c['revenue_delivery_ratio'], '.2f') + '×'} |")
    L += ["", f"Universe base rate (weighted delivery credit): {sc['base_rate']}", ""]
    if md:
        ev = md["evaluation"]
        lo, wf = ev["loco"], ev.get("walk_forward")
        L += ["## Predicting whether a promise will be kept", "",
              f"- {ev['n']} resolved promises, {ev['kept_rate']:.0%} fully kept",
              f"- Leave-one-company-out AUC **{lo['auc_model']:.3f}** (90% CI {lo['auc_ci90']}); "
              f"company Say-Do score alone {lo['auc_prior_score_only']}; Brier {lo['brier_model']:.3f} vs base rate {lo['brier_base_rate']:.3f}"]
        if wf:
            L.append(f"- Walk-forward (train on outcomes public before {wf['cutoff']}, n={wf['train']}; "
                     f"test on later promises, n={wf['test']}): AUC **{wf['auc_model']:.3f}** (90% CI {wf['auc_ci90']}); "
                     f"score-only {wf['auc_prior_score_only']}; Brier {wf['brier_model']:.3f} vs {wf['brier_base_rate']:.3f}")
        L += ["", "Top coefficients (positive = more likely kept):", ""]
        L += [f"- `{k}` {v:+.2f}" for k, v in md["coefficients"] if k != "bias"][:10]
        L.append("")
    if mk:
        cs, es = mk["cross_section"], mk["event_study"]
        L += ["## Market test (point-in-time, excess vs equal-weight universe)", ""]
        if cs.get("spread_pct") is not None:
            L.append(f"- {cs['events']} call-events, {cs['companies']} companies: top-tercile Say-Do "
                     f"{cs['top_tercile_excess']:+.2f}% vs bottom {cs['bottom_tercile_excess']:+.2f}% over "
                     f"{cs['hold_days']} days; spread {cs['spread_pct']:+.2f}% (90% CI {cs['spread_ci90_pct']}); "
                     f"mean quarterly rank IC {cs['mean_ic']}")
        else:
            L.append(f"- cross-section: {cs.get('note')}")
        if es.get("diff_pct") is not None:
            L.append(f"- Event study ({es['days']}d): kept revealed {es['kept_excess_pct']:+.2f}% (n={es['kept_events']}), "
                     f"broken revealed {es['broken_excess_pct']:+.2f}% (n={es['broken_events']}), diff {es['diff_pct']:+.2f}% "
                     f"(90% CI {es['diff_ci90_pct']})")
        L += ["", "Intervals that include zero mean the test is inconclusive at this sample size.", ""]
    au = _l("audit.json")
    L += ["## Judge accuracy (human audit)", "",
          (f"- {au['labelled']} outcomes hand-checked: exact agreement {au['exact_agreement']:.0%}, "
           f"kept-vs-not agreement {au['kept_vs_not_agreement']:.0%}; per outcome {au['per_model_outcome']}")
          if au else "- Not yet audited: run `python -m saydo.audit sample`, label the CSV, then `python -m saydo.audit score`.", ""]
    de = _l("distill_eval.json")
    if de:
        L += ["## Llama student vs Muse teacher (held-out calls)", "", f"- {de}", ""]
    open(os.path.join(config.ROOT, "RESULTS.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
